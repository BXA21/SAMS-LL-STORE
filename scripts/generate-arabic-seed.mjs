// Regenerates the Arabic-content migration from src/i18n/arabicContent.ts so the
// database seed and the in-app fallback copy can never drift apart.
// Usage: node --experimental-strip-types scripts/generate-arabic-seed.mjs
import { writeFileSync } from 'node:fs';
import { PRODUCT_AR, CATEGORY_AR, FAQ_AR, TESTIMONIAL_AR } from '../src/i18n/arabicContent.ts';

const OUT = 'supabase/migrations/20261001100000_arabic_content_translations.sql';
const TAG = '$ar$';

function literal(text) {
  if (text.includes(TAG)) throw new Error(`content contains the quote tag ${TAG}`);
  return `${TAG}${text}${TAG}`;
}

function jsonb(ar) {
  return `jsonb_build_object('ar', ${literal(JSON.stringify(ar))}::jsonb)`;
}

const lines = [
  '-- Arabic storefront copy. GENERATED by scripts/generate-arabic-seed.mjs from',
  '-- src/i18n/arabicContent.ts. Do not edit by hand.',
  '--',
  '-- Each content table gets a `translations` jsonb object ({ "ar": { ... } }).',
  "-- Seeded rows are filled only while their translations are still empty, so",
  '-- re-running this never overwrites Arabic copy staff edited in the dashboard.',
  '',
];

for (const table of ['products', 'categories', 'faqs', 'testimonials']) {
  lines.push(
    `alter table public.${table} add column if not exists translations jsonb not null default '{}'::jsonb;`,
    `alter table public.${table} drop constraint if exists ${table}_translations_is_object;`,
    `alter table public.${table} add constraint ${table}_translations_is_object check (jsonb_typeof(translations) = 'object' and pg_column_size(translations) < 65536);`,
    '',
  );
}

const update = (table, ar, column, key) =>
  `update public.${table} set translations = ${jsonb(ar)} where ${column} = ${literal(key)} and translations = '{}'::jsonb;`;

for (const [slug, ar] of Object.entries(PRODUCT_AR)) lines.push(update('products', ar, 'slug', slug));
lines.push('');
for (const [slug, ar] of Object.entries(CATEGORY_AR)) lines.push(update('categories', ar, 'slug', slug));
lines.push('');
for (const [question, ar] of Object.entries(FAQ_AR)) lines.push(update('faqs', ar, 'question', question));
lines.push('');
for (const [name, ar] of Object.entries(TESTIMONIAL_AR)) lines.push(update('testimonials', ar, 'name', name));
lines.push('');

writeFileSync(OUT, lines.join('\n'), 'utf8');
console.log(`wrote ${OUT}`);
